const LANDMARKS = {
  malioboro: { lat: -7.79302, lng: 110.36559, nama: "Malioboro" },
  kraton: { lat: -7.80532, lng: 110.36427, nama: "Kraton Yogyakarta" },
  tamanSari: { lat: -7.80992, lng: 110.35922, nama: "Taman Sari" },
  vredeburg: { lat: -7.79453, lng: 110.3658, nama: "Benteng Vredeburg" },
  alunAlun: { lat: -7.8012, lng: 110.3643, nama: "Alun-alun Utara" },
};

const WSM_WEIGHTS = {
  malioboro: 0.25,
  kraton: 0.2,
  tamanSari: 0.15,
  vredeburg: 0.1,
  alunAlun: 0.1,
  bintang: 0.2,
};

/* Rumus Haversine — standar perhitungan jarak geodetik dalam GIS */
function haversineKm(lat1, lng1, lat2, lng2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

/* Hitung jarak satu hotel ke semua landmark */
function hitungJarakLandmark(hotel) {
  const hasil = {};
  Object.entries(LANDMARKS).forEach(([key, lm]) => {
    hasil[key] = haversineKm(hotel.lat, hotel.lng, lm.lat, lm.lng);
  });
  return hasil;
}

/* Normalisasi & hitung WSM untuk semua hotel sekaligus */
function hitungWSM(hotelsRaw) {
  /* Step 1 — hitung jarak semua hotel ke semua landmark */
  const jarakData = hotelsRaw.map((h) => hitungJarakLandmark(h));

  /* Step 2 — cari nilai maksimum per landmark untuk normalisasi */
  const maxJarak = {};
  Object.keys(LANDMARKS).forEach((key) => {
    maxJarak[key] = Math.max(...jarakData.map((d) => d[key]));
  });

  /* Step 3 — hitung skor WSM tiap hotel */
  return hotelsRaw.map((h, i) => {
    const jarak = jarakData[i];

    /* Normalisasi jarak: makin dekat = makin tinggi skor */
    const n_malio = 1 - jarak.malioboro / maxJarak.malioboro;
    const n_kraton = 1 - jarak.kraton / maxJarak.kraton;
    const n_taman = 1 - jarak.tamanSari / maxJarak.tamanSari;
    const n_vreden = 1 - jarak.vredeburg / maxJarak.vredeburg;
    const n_alun = 1 - jarak.alunAlun / maxJarak.alunAlun;

    /* Normalisasi bintang: bintang 1→0.0, bintang 5→1.0 */
    const n_bintang = (h.stars - 1) / 4;

    const raw =
      WSM_WEIGHTS.malioboro * n_malio +
      WSM_WEIGHTS.kraton * n_kraton +
      WSM_WEIGHTS.tamanSari * n_taman +
      WSM_WEIGHTS.vredeburg * n_vreden +
      WSM_WEIGHTS.alunAlun * n_alun +
      WSM_WEIGHTS.bintang * n_bintang;

    return {
      ...h,
      wsm: +(raw * 10).toFixed(2),
      jarakLandmark: {
        malioboro: +jarak.malioboro.toFixed(2),
        kraton: +jarak.kraton.toFixed(2),
        tamanSari: +jarak.tamanSari.toFixed(2),
        vredeburg: +jarak.vredeburg.toFixed(2),
        alunAlun: +jarak.alunAlun.toFixed(2),
      },
      wsmKomponen: {
        malioboro: +(n_malio * WSM_WEIGHTS.malioboro * 10).toFixed(2),
        kraton: +(n_kraton * WSM_WEIGHTS.kraton * 10).toFixed(2),
        tamanSari: +(n_taman * WSM_WEIGHTS.tamanSari * 10).toFixed(2),
        vredeburg: +(n_vreden * WSM_WEIGHTS.vredeburg * 10).toFixed(2),
        alunAlun: +(n_alun * WSM_WEIGHTS.alunAlun * 10).toFixed(2),
        bintang: +(n_bintang * WSM_WEIGHTS.bintang * 10).toFixed(2),
      },
    };
  });
}

